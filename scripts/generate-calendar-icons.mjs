// Maintenance only: node scripts/generate-calendar-icons.mjs (Node >= 22.18).
// Uses the already installed FREE icons. Never fetches from a CDN or API.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CALENDAR_ICON_RULES } from '../src/lib/calendar-icon-rules.ts';

const root = new URL('../', import.meta.url);
const names = [...new Set(['calendar-days', ...CALENDAR_ICON_RULES.map(rule => rule.icon)])].sort();
const paths = {};
for (const name of names) {
  const svg = await readFile(new URL(`node_modules/@fortawesome/fontawesome-free/svgs/solid/${name}.svg`, root), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const shapes = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(match => match[1]);
  if (!viewBox || shapes.length === 0) throw new Error(`SVG nicht lesbar: ${name}`);
  paths[name] = { viewBox, paths: shapes };
}
const attribution = '// Generated by scripts/generate-calendar-icons.mjs. Do not edit paths by hand.\n'
  + '// Font Awesome Free by Fonticons, Inc. — icons: CC BY 4.0.\n'
  + '// https://fontawesome.com/license/free | https://creativecommons.org/licenses/by/4.0/\n';
await writeFile(new URL('src/lib/calendar-icon-paths.ts', root), attribution
  + `export const CALENDAR_ICON_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`
  + 'export type CalendarIconName = keyof typeof CALENDAR_ICON_PATHS;\n');
const count = CALENDAR_ICON_RULES.reduce((total, rule) => total + rule.aliases.length, 0);
let doc = `# Automatische Kalendersymbole\n\n${CALENDAR_ICON_RULES.length} Zuordnungen, ${count} Begriffe und Schreibvarianten, ${names.length} lokale SVG-Symbole.\n\n`
  + 'Die deutsche Matrix ist eine eigene redaktionelle Zuordnung. iCalendar definiert Kategorien, aber keine allgemeine Wort-zu-Symbol-Matrix. '
  + 'Die Begriffe sind für den Familienalltag kuratiert, keine importierten Familiendaten.\n\n'
  + '## Verhalten\n\n'
  + '- Der Titel hat Vorrang vor einer allgemeinen Kategorie. Spezifische Aktivitäten gewinnen vor den allgemeinen Regeln Training, Schule, Arbeit und Freizeit (z. B. Yoga vor Training). Danach entscheiden die längere passende Wortgruppe und schließlich die Reihenfolge dieser Matrix.\n'
  + '- Groß-/Kleinschreibung, Umlaute (auch ae/oe/ue), ß/ss und Satzzeichen werden vereinheitlicht. Nur ganze Wörter oder Wortgruppen zählen: „Ball“ trifft nicht „Ballon“. Zusammengesetzte Wörter sind ausdrücklich hinterlegt.\n'
  + '- Wenn im Titel nichts erkannt wird, dienen Kategorie Schule, Arbeit, Freizeit, Arzt, Familie und weitere unten dokumentierte Kategorien als Rückfall. Ohne Treffer erscheint ein neutrales Kalendersymbol.\n'
  + '- Bestehende farbige Mülltonnen und die bisherigen Geburtstagstorten haben Vorrang in Kalender und Startansicht. Personenfarben bleiben erhalten.\n'
  + '- Es wird nur die Darstellung abgeleitet: keine Änderung gespeicherter Termine, kein Schemawechsel, keine Migration, keine Netzabfragen. Neue Regeln wirken auf bestehende Termine.\n'
  + '- Keine Sprach-KI: Verneinungen, Tippfehler und unbekannte Zusammensetzungen werden nicht semantisch verstanden. Bei mehreren Aktivitäten kann nur ein Symbol angezeigt werden.\n\n'
  + '## Pflege\n\n'
  + '`src/lib/calendar-icon-rules.ts` enthält die Regeln; `calendar-icon-mapping.ts` die Erkennung und Kategorie-Rückfälle. '
  + 'Nach Regeländerungen `node scripts/generate-calendar-icons.mjs` ausführen (Node ≥ 22.18, npm-Abhängigkeiten installiert). '
  + 'Der Generator aktualisiert diese Tabelle und extrahiert ausschließlich benötigte freie SVG-Pfade. Keine neuen Abhängigkeiten. '
  + 'Unter **Mehr → Kalendersymbole** lässt sich die Matrix durchsuchen; im Terminformular erscheint eine Vorschau.\n\n'
  + '## Quellen und Lizenz\n\n'
  + '- [Font Awesome: lokale SVG-Verwendung](https://docs.fontawesome.com/web/add-icons/svg-bare)\n'
  + '- [Font Awesome Free: Lizenz](https://fontawesome.com/license/free), SVG-Icons von Fonticons, Inc., CC BY 4.0. Pfade aus dem installierten Paket, Form unverändert; Darstellung mit aktueller Textfarbe.\n'
  + '- [RFC 5545, CATEGORIES](https://www.rfc-editor.org/rfc/rfc5545.html#section-3.8.1.2)\n\n';
for (const category of new Set(CALENDAR_ICON_RULES.map(rule => rule.group))) {
  doc += `## ${category}\n\n| Zuordnung | SVG-Symbol | Erkannte Begriffe |\n|---|---|---|\n`;
  for (const rule of CALENDAR_ICON_RULES.filter(rule => rule.group === category)) {
    doc += `| ${rule.label} | ${rule.icon} | ${rule.aliases.join(', ')} |\n`;
  }
  doc += '\n';
}
await writeFile(new URL('docs/CALENDAR-ICON-MATRIX.md', root), doc);
console.log(`${CALENDAR_ICON_RULES.length} Zuordnungen, ${count} Begriffe, ${names.length} SVGs: ${fileURLToPath(root)}`);
