import type { CalendarIconName } from './calendar-icon-paths';

export type CalendarIconRule = {
  id: string;
  group: string;
  label: string;
  icon: CalendarIconName;
  aliases: readonly string[];
};
type Entry = readonly [CalendarIconName, string, string];
function group(name: string, entries: readonly Entry[]): CalendarIconRule[] {
  return entries.map(([icon, label, aliases]) => ({
    id: `${name}/${label}`, group: name, label, icon,
    aliases: [...new Set([label, ...aliases.split('|')].filter(Boolean))],
  }));
}

